/// The kinds of things Vinyasa knows how to place: typical sizes, the clear
/// space each needs to be used, and the tags rules match on. Sizes are
/// common retail sizes in millimetres; the user can change any item's own.
/// Clearances follow the research notes in docs/rules.md.
library;

enum KindGroup {
  sleep('Sleep'),
  seating('Seating'),
  tables('Tables'),
  storage('Storage'),
  work('Work'),
  kitchen('Kitchen'),
  bath('Bath'),
  media('Media'),
  decor('Decor and light'),
  worship('Worship'),
  business('Business'),
  other('Other');

  const KindGroup(this.label);
  final String label;
}

/// How strongly an item wants its back to a wall.
enum WallNeed { none, prefer, must }

class ItemKind {
  const ItemKind(
    this.id,
    this.label,
    this.group, {
    required this.w,
    required this.d,
    this.h = 750,
    this.front = 0,
    this.side = 0,
    this.wall = WallNeed.none,
    this.blocks = true,
    this.heavy = false,
    this.tags = const {},
  });

  final String id, label;
  final KindGroup group;

  /// Typical width (along the front), depth and height.
  final int w, d, h;

  /// Clear depth needed in front to use it (open a door, pull a chair, stand).
  final int front;

  /// Clear width needed on each side (getting into a bed).
  final int side;
  final WallNeed wall;

  /// Whether it stops people walking (a rug or wall art does not).
  final bool blocks;

  /// Needs two people to move.
  final bool heavy;
  final Set<String> tags;

  bool has(String tag) => tags.contains(tag);

  /// Plumbed or built in: new items of these kinds start fixed in place.
  bool get builtIn => const {
    'counter',
    'hob',
    'sink',
    'dishwasher',
    'toilet',
    'basin',
    'shower',
    'washing_machine',
  }.contains(id);
}

